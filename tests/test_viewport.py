"""The one-viewport budget (v109) — the incident screen is one HTML document.

The screen is generated by incident_html.build() and embedded as a single component, so the layout
contract lives in that string: four tiles, six tabs, a graph with observed and inferred edges, no
absolute positioning outside the SVG, and no duplicated section.
"""
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.chdir(ROOT)

import incident_html  # noqa: E402
import journey  # noqa: E402
import sqlite3  # noqa: E402


def html_for(ref="INC-8841", tab="Timeline"):
    import dataops_engine as DE
    import engine as E
    con = sqlite3.connect(ROOT / "data" / "ops.db")
    con.row_factory = sqlite3.Row
    table = "dop_incidents" if ref.startswith("DOP") else "incidents"
    inc = dict(con.execute(f"SELECT * FROM {table} WHERE id=?", (ref,)).fetchone())
    con.close()
    if ref.startswith("DOP"):
        leads, headline = journey.leads_for(inc, DE.causes(inc, DE.load()))
    else:
        sv, _ed, _incs, ch, me, G = E.load()
        leads, headline = journey.leads_for(inc, E.causes(inc, G, ch, me, sv))
    return incident_html.build(inc, "DataOps" if ref.startswith("DOP") else "IT Ops",
                               queue="1 of 7", initial_tab=tab, leads=leads, headline=headline)


def test_the_tiles_are_exactly_the_four_labels():
    labels = re.findall(r'<div class="k">([^<]+)</div>', html_for())
    assert labels == ["Waiting on", "Error rate", "Data freshness", "Checkout"], labels


def test_the_graph_shows_observed_and_inferred_edges_with_confidence():
    h = html_for()
    graph = h[h.index("Why this is happening"):h.index("What this means")]
    assert "stroke-dasharray" in graph, "an inferred edge is dashed"
    assert graph.count('marker-end="url(#as)"') >= 3, "observed edges are solid"
    assert graph.count('marker-end="url(#ad)"') >= 1
    for label in ("inferred 0.72", "writes 0.85", "stale 0.85", "feeds 0.95"):
        assert label in graph, f"edge confidence missing: {label}"
    assert "observed" in graph and "inferred" in graph
    assert "connections" in graph


def test_the_six_tabs_carry_state_in_words():
    h = html_for()
    import html as _h
    for name in incident_html.TAB_NAMES:
        assert f'>{_h.escape(name)}<b>' in h, f"tab missing: {name}"
    assert "OVERDUE" in h or "none overdue" in h
    assert "BLOCKED" in h or "ready" in h or "closed" in h


def test_no_absolute_positioning_outside_the_svg():
    css = html_for()
    css = css[css.index("<style>"):css.index("</style>")]
    assert "position:absolute" not in css, "the brief forbids absolute positioning outside the graph"


def test_no_section_is_rendered_twice():
    h = html_for()
    assert h.count('<div class="tile"') == 4
    assert h.count('class="tab on"') == 1, "exactly one tab is active on load"
    assert h.count('class="pane on"') == 1, "exactly one pane is rendered visible"
    assert h.count("Why this is happening") >= 1


def test_a_tab_can_be_selected_on_load():
    h = html_for(tab="Learn")
    assert re.search(r'class="pane on" id="p5"', h), "the requested tab opens"
    assert re.search(r'class="tab on" data-t="5"', h)


def test_no_negative_margins_and_no_absolute_positioning_outside_the_svg():
    """The class of bug that produced the overlaps: negative margins and absolute layout."""
    h = html_for()
    css = h[h.index("<style>"):h.index("</style>")]
    assert not re.search(r"margin[a-z-]*:\s*-\d", css), "no negative margins"
    assert "position:absolute" not in css and "position:fixed" not in css, \
        "nothing is taken out of flow; the graph uses SVG coordinates only"
    assert "<svg" in h and "viewBox" in h, "the graph positions by viewBox, not by CSS"


def test_the_panes_render_for_every_tab():
    for i, name in enumerate(incident_html.TAB_NAMES):
        h = html_for(tab=name)
        pane = re.search(rf'class="pane on" id="p{i}">(.*?)<button class="more"', h, re.S)
        assert pane and len(pane.group(1).strip()) > 40, f"{name} pane is empty"


# ---------------------------------------------------------------- restored controls
# The incident screen is assembled from controls that are restored one pass at a time. Each entry is
# one control that is live in THIS build; a later pass adds its rows instead of rewriting an
# assertion that used to say "exactly one action". ``verbs`` is the full set of actions the document
# may carry — an action that appears and is not listed here is a control that was added without a
# line of cover, and fails.
RESTORED_CONTROLS = [
    ("back to the list", "action=back", lambda h: True),
    ("chase (hero)", "action=chase", lambda h: True),
    ("confirm cause", "action=confirm", lambda h: True),
    ("requests · acknowledge", "action=ack&amp;target=", lambda h: 'class="rrow"' in h),
    ("requests · mark done", "action=done&amp;target=", lambda h: 'class="rrow"' in h),
    ("requests · send (NOT SENT)", "action=send&amp;target=", lambda h: "NOT SENT" in h),
    ("requests · create ask (opens the form)", "new=1", lambda h: True),
    ("rca · confirm lead", "action=confirm-lead&amp;target=", lambda h: 'class="lead"' in h),
    ("rca · reject lead", "action=reject-lead&amp;target=", lambda h: 'class="lead"' in h),
    ("rca · set aside", "action=set-aside&amp;target=", lambda h: 'class="lead"' in h),
    ("close gate", "Close incident", lambda h: True),
]

# Every action verb the document is allowed to carry in v111.
KNOWN_VERBS = {"back", "chase", "confirm", "ack", "done", "send", "ask",
               "confirm-lead", "reject-lead", "set-aside", "close"}


def test_every_restored_control_offers_its_action():
    h = html_for(tab="Requests")
    missing = [name for name, frag, applies in RESTORED_CONTROLS if applies(h) and frag not in h]
    assert not missing, f"restored controls with no control on screen: {missing}"
    verbs = set(re.findall(r"action=([a-z-]+)", h))
    assert verbs <= KNOWN_VERBS, f"unlisted action verbs in the document: {verbs - KNOWN_VERBS}"
    # a lead action must name the lead it acts on, or it is not a control
    for lead_href in re.findall(r'href="(\?[^"]*action=(?:confirm-lead|reject-lead|set-aside)[^"]*)"', h):
        assert "target=" in lead_href, lead_href


def test_the_who_row_states_asked_once():
    h = html_for()
    row = h[h.index("Who is on it"):]
    assert row.count(">asked<") <= 1, "the 'asked' label appears once per row"
    assert "asked" not in re.sub(r">asked<", "", row)
