"""The one-viewport budget (v109) — the incident screen is one HTML document.

The screen is generated by incident_html.build() and embedded as a single component, so the layout
contract lives in that string: four tiles, six tabs, a graph with observed and inferred edges, no
absolute positioning outside the SVG, and no duplicated section.
"""
import os
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
os.chdir(ROOT)

import incident_html  # noqa: E402
import journey  # noqa: E402
import sqlite3  # noqa: E402


def html_for(ref="INC-8841", tab="Timeline"):
    con = sqlite3.connect(ROOT / "data" / "ops.db")
    con.row_factory = sqlite3.Row
    table = "dop_incidents" if ref.startswith("DOP") else "incidents"
    inc = dict(con.execute(f"SELECT * FROM {table} WHERE id=?", (ref,)).fetchone())
    con.close()
    return incident_html.build(inc, "DataOps" if ref.startswith("DOP") else "IT Ops",
                               queue="1 of 7", initial_tab=tab)


def test_the_tiles_are_exactly_the_four_labels():
    labels = re.findall(r'<div class="k">([^<]+)</div>', html_for())
    assert labels == ["Waiting on", "Error rate", "Data freshness", "Checkout"], labels


def test_the_graph_shows_observed_and_inferred_edges_with_confidence():
    h = html_for()
    graph = h[h.index("Why this is happening"):h.index("What this means")]
    assert "stroke-dasharray" in graph, "an inferred edge is dashed"
    assert graph.count('marker-end="url(#as)"') >= 3, "observed edges are solid"
    assert graph.count('marker-end="url(#ad)"') >= 1
    for label in ("inferred 0.72", "writes 0.85", "stale 0.85", "feeds 0.95"):
        assert label in graph, f"edge confidence missing: {label}"
    assert "observed" in graph and "inferred" in graph
    assert "connections" in graph


def test_the_six_tabs_carry_state_in_words():
    h = html_for()
    import html as _h
    for name in incident_html.TAB_NAMES:
        assert f'>{_h.escape(name)}<b>' in h, f"tab missing: {name}"
    assert "OVERDUE" in h or "none overdue" in h
    assert "BLOCKED" in h or "ready" in h or "closed" in h


def test_no_absolute_positioning_outside_the_svg():
    css = html_for()
    css = css[css.index("<style>"):css.index("</style>")]
    assert "position:absolute" not in css, "the brief forbids absolute positioning outside the graph"


def test_no_section_is_rendered_twice():
    h = html_for()
    assert h.count('<div class="tile"') == 4
    assert h.count('class="tab on"') == 1, "exactly one tab is active on load"
    assert h.count('class="pane on"') == 1, "exactly one pane is rendered visible"
    assert h.count("Why this is happening") >= 1


def test_a_tab_can_be_selected_on_load():
    h = html_for(tab="Learn")
    assert re.search(r'class="pane on" id="p5"', h), "the requested tab opens"
    assert re.search(r'class="tab on" data-t="5"', h)
