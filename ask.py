#!/usr/bin/env python3
"""Ask — natural-language questions, answered only from stored definitions.

This is a credibility feature, not a chatbot. A question is parsed into a small intent schema; the
intent is executed against the database with the *same* computations the Analytics page uses
(`analytics.created_between`, `analytics.mttr_between`, `analytics.held_by_domain`) or against the
incident record (`story`). Nothing is generated by a model, and nothing is answered from prose.

If the question does not resolve to one of those intents, the answer is a refusal that names what
can be answered. A number is never guessed and never estimated.
"""
import datetime as dt
import re

import analytics
import collab
import journey
import story

DB = story.DB  # rebound by app.py with the rest

# The three examples a refusal offers — and the chips under it.
EXAMPLES = [
    "how many incidents were reported yesterday",
    "summarise INC-8841",
    "what is our median resolution time this week",
]

INTENTS = ("count", "summary", "held_longest", "median_resolution")

_INC = re.compile(r"\b(INC-\d+|DOP-\d+)\b", re.I)
_N_DAYS = re.compile(r"last\s+(\d{1,3})\s+days?")

WINDOW_LABEL = {"today": "today", "yesterday": "yesterday", "this week": "this week",
                "last week": "the last 7 days", "this month": "this month",
                "last month": "the last 30 days", "all": "all time"}


# ------------------------------------------------------------------ time windows
def window(name, now=None):
    """(start, end, label) for a named window. Rolling windows are stated in the interpretation
    line, so 'last week' never silently means a calendar week."""
    now = now or dt.datetime.now().replace(microsecond=0)
    today = now.replace(hour=0, minute=0, second=0, microsecond=0)
    if name == "today":
        return today, now, "today"
    if name == "yesterday":
        return today - dt.timedelta(days=1), today, "yesterday"
    if name == "this week":
        return today - dt.timedelta(days=now.weekday()), now, "this week"
    if name == "last week":
        return today - dt.timedelta(days=6), now, "the last 7 days"
    if name == "this month":
        return today.replace(day=1), now, "this month"
    if name == "last month":
        return today - dt.timedelta(days=30), now, "the last 30 days"
    m = re.match(r"last (\d+) days", name or "")
    if m:
        return today - dt.timedelta(days=int(m.group(1)) - 1), now, f"the last {m.group(1)} days"
    return None, None, "all time"


def _window_name(text):
    if "yesterday" in text:
        return "yesterday"
    if "today" in text:
        return "today"
    if "this week" in text:
        return "this week"
    if "last week" in text:
        return "last week"
    if "this month" in text:
        return "this month"
    if "last month" in text:
        return "last month"
    m = _N_DAYS.search(text)
    if m:
        return f"last {m.group(1)} days"
    return "all"


def _stamp(start, end):
    if start is None:
        return "every incident on record"
    if (end - start) <= dt.timedelta(days=1) and end.hour == 0 and end.minute == 0:
        return f'between {start:%d %b %H:%M} and {(end - dt.timedelta(minutes=1)):%d %b %H:%M}'
    return f'between {start:%d %b %H:%M} and {end:%d %b %H:%M}'


STATUS_PHRASE = {"all": "all statuses", "open": "open only", "closed": "closed only",
                 "failed": "with a failed recovery"}


# ------------------------------------------------------------------ intent parsing
def parse(question):
    """Question → intent. Pure string work; no database access, so it is cheap to test."""
    text = (question or "").strip()
    low = text.lower()

    if not low:
        return {"intent": "unsupported", "why": "empty question"}

    m = _INC.search(text)
    summary_words = ("summar", "what happened", "recap", "story", "walk me through", "timeline of")
    if m and any(w in low for w in summary_words):
        return {"intent": "summary", "ref": m.group(1).upper()}
    if m:
        return {"intent": "unsupported", "why": f"{m.group(1).upper()} is an incident, not a metric",
                "hint": f"try 'summarise {m.group(1).upper()}'"}

    if ("how many" in low or "number of" in low) and any(
            w in low for w in ("incident", "reported", "failed", "failure", "raised")):
        status = "all"
        if "failed" in low or "failure" in low:
            status = "failed"
        elif "open" in low:
            status = "open"
        elif "closed" in low or "resolved" in low:
            status = "closed"
        return {"intent": "count", "window": _window_name(low), "status": status}

    if any(w in low for w in ("median", "average", "typical")) and any(
            w in low for w in ("resolution", "resolve", "mttr", "time to close", "close time")):
        return {"intent": "median_resolution", "window": _window_name(low)}

    if any(w in low for w in ("which domain", "held us", "held the", "slowest", "longest")) and \
            ("domain" in low or "held" in low or "slow" in low):
        return {"intent": "held_longest", "window": _window_name(low)}

    return {"intent": "unsupported", "why": "no stored definition matches this question"}


# ------------------------------------------------------------------ answers
def _count(intent, now=None):
    start, end, label = window(intent["window"], now)
    status = intent.get("status", "all")
    r = analytics.created_between(start.isoformat(timespec="seconds") if start else None,
                                  end.isoformat(timespec="seconds") if end else None, status)
    interp = (f'Incidents created {_stamp(start, end)}, {STATUS_PHRASE[status]}' if start
              else f'Incidents on record, {STATUS_PHRASE[status]}')
    return {
        "ok": True, "intent": "count",
        "interpretation": interp,
        "headline": str(r["n"]),
        "n": r["n"],
        "n_label": f'matched · {r["checked"]} incidents on record',
        "narrative": [],
        "cites": [{"ts": row["created_at"], "detail": f'{row["id"]} · {row["status"]}'}
                  for row in r["rows"]],
        "cites_label": "Matching incidents",
        "sql": r["sql"], "params": r["params"],
        "based_on": "incidents, dop_incidents, resolution_state · definition: created_at window, "
                    "status bucket (analytics.created_between)",
        "followups": [
            f'same question, {("the last 30 days" if label != "the last 30 days" else "all time")}',
            f'how many incidents are open',
            "what is our median resolution time this week",
        ],
    }


def _median(intent, now=None):
    start, end, label = window(intent["window"], now)
    r = analytics.mttr_between(start.isoformat(timespec="seconds") if start else None,
                               end.isoformat(timespec="seconds") if end else None)
    interp = (f'Median of closed_at − created_at for verified closures {_stamp(start, end)}')
    return {
        "ok": True, "intent": "median_resolution",
        "interpretation": interp,
        "headline": f'{r["median_min"]:g} min' if r["median_min"] is not None else "—",
        "n": r["n"],
        "n_label": f'verified closures · p90 {r["p90_min"]:g} min' if r["n"] else "no verified closure in this window",
        "narrative": [] if r["n"] else _no_closure_text(),
        "cites": [{"ts": None, "detail": f'{v:g} min'} for v in r["values"]],
        "cites_label": "Closures measured",
        "sql": r["sql"], "params": r["params"],
        "based_on": "resolution_state (verdict = Verified, closed_at) × incidents/dop_incidents.created_at "
                    "· the same filter as the Analytics MTTR panel (analytics.mttr_between)",
        "followups": (["which domain held us longest last month",
                       "how many incidents were reported yesterday",
                       "how many failed in the last week"] if r["n"] else
                      ["what is our median resolution time in the last 30 days",
                       "how many incidents were closed in the last 30 days",
                       "summarise INC-8802"]),
    }


def _no_closure_text():
    """When a window has no verified closure, say when the last one was — a dash plus a route."""
    rows = story._rows("SELECT ref_id, closed_at FROM resolution_state "
                       "WHERE verdict='Verified' AND closed_at IS NOT NULL "
                       "ORDER BY closed_at DESC LIMIT 1")
    if not rows:
        return ["No verified closure exists on this system yet, so the median is not computed."]
    try:
        when = dt.datetime.fromisoformat(rows[0]["closed_at"]).strftime("%d %b %H:%M")
    except Exception:
        when = rows[0]["closed_at"]
    return [f'No verified closure falls in this window, so the median is not computed — a missing '
            f'record is unknown, not zero. The most recent verified closure was '
            f'{rows[0]["ref_id"]} at {when}; widen the window to include it.']


def _held(intent, now=None):
    start, end, label = window(intent["window"], now)
    r = analytics.held_by_domain(start.isoformat(timespec="seconds") if start else "0000-01-01T00:00:00",
                                 end.isoformat(timespec="seconds") if end else "9999-12-31T00:00:00")
    top = r["rows"][0] if r["rows"] else None
    interp = (f'Minutes incidents spent waiting on each domain, for requests raised {_stamp(start, end)}')
    if not top:
        return {
            "ok": True, "intent": "held_longest", "interpretation": interp,
            "headline": "—", "n": 0, "n_label": "no request raised in this window",
            "narrative": ["No request was raised in this window, so no domain held the work."],
            "cites": [], "sql": r["sql"], "params": r["params"],
            "based_on": "delegations (ts → done_at, or now when open) · analytics.held_by_domain",
            "followups": ["which domain held us longest last month",
                          "how many incidents were reported yesterday"],
        }
    others = [d for d in r["rows"][1:]]
    narrative = [
        f'{top["domain"]} held the work longest: {top["minutes"]:g} min across {top["requests"]} '
        f'request(s).'
        + (" Next: " + " · ".join(f'{d["domain"]} {d["minutes"]:g} min' for d in others) if others else "")
    ]
    return {
        "ok": True, "intent": "held_longest", "interpretation": interp,
        "headline": top["domain"], "n": r["n"],
        "n_label": f'requests measured · {top["minutes"]:g} min waiting',
        "narrative": narrative,
        "cites": [{"ts": None, "detail": f'{t["team"]} · {t["requests"]} request(s) · {t["minutes"]:g} min'}
                  for t in r["teams"]],
        "cites_label": "Requests by team",
        "sql": r["sql"], "params": r["params"],
        "based_on": "delegations (ts, done_at) joined on the incident id · analytics.held_by_domain",
        "followups": ["how many incidents were reported yesterday",
                      "how many failed in the last week",
                      "what is our median resolution time this week"],
    }


def _summary(ref, now=None):
    con = story._con()
    inc = None
    for table in ("incidents", "dop_incidents"):
        row = con.execute(f"SELECT * FROM {table} WHERE id=?", (ref,)).fetchone()
        if row:
            inc = dict(row)
            break
    con.close()
    if inc is None:
        return {"ok": False, "intent": "summary", "question_ref": ref,
                "interpretation": f"No incident {ref} exists on this system.",
                "headline": "—", "n": 0, "n_label": "", "narrative": [],
                "cites": [], "sql": None, "params": {},
                "based_on": "incidents, dop_incidents",
                "followups": EXAMPLES}

    events = story._rows("SELECT kind, detail, ts FROM timeline WHERE ref_id=? ORDER BY ts", (ref,))
    h = story.hero(inc)
    a = story.acceleration(inc)
    chain = story.chain(inc)
    holder = next((n for n in chain if n.get("holder")), None)

    def at(ts):
        try:
            return dt.datetime.fromisoformat(ts).strftime("%H:%M")
        except Exception:
            return str(ts)

    hours = [e for e in events if e["kind"] in ("alert", "incident")]
    narrative = [f'{inc.get("title") or ref}. Raised at {at(inc["created_at"])} as {inc["priority"]}, '
                 f'owner {inc.get("owner_team") or "unassigned"}.']
    if hours:
        narrative.append("What happened: " + " · ".join(
            f'{at(e["ts"])} {e["detail"]}' for e in hours[:3]) + ".")
    if holder:
        narrative.append(f'Who held it: {holder["label"]} — {holder["clock"]}, '
                         f'{h["cross"]["handoffs"]} handoff(s) across {h["cross"]["domains"]} domains.')
    if a["unblocked_by_evidence_min"] is not None:
        narrative.append(f'What unblocked it: {a["unblocked_by_evidence_what"]} '
                         f'({a["unblocked_by_evidence_min"]}m after the request was raised).')
    if a["time_to_next_action_min"] is not None:
        narrative.append(f'First action {a["time_to_next_action_min"]}m after the alarm — '
                         f'{a["time_to_next_action_what"]}.')
    rec = story._rows("SELECT verdict, closed_at FROM resolution_state WHERE ref_id=?", (ref,))
    if rec and rec[0].get("closed_at"):
        mins = story.minutes_between(inc["created_at"], rec[0]["closed_at"])
        narrative.append(f'Closed {at(rec[0]["closed_at"])} after {story.fmt_minutes(mins)} — '
                         f'verdict {rec[0]["verdict"]}.')
    else:
        narrative.append(f'Still open — {inc.get("stage")}, SLA {h["sla"]["text"]}.')

    return {
        "ok": True, "intent": "summary", "ref": ref,
        "interpretation": f'The recorded thread of {ref}, in order: raise, signals, holder, '
                          f'what unblocked it, and how it ended',
        "headline": ref, "n": len(events),
        "n_label": f'events cited · {len(chain)} hops',
        "narrative": narrative,
        "cites": [{"ts": e["ts"], "detail": e["detail"]} for e in events],
        "cites_label": "Events cited",
        "sql": ("SELECT kind, detail, ts FROM timeline WHERE ref_id = :ref ORDER BY ts;\n"
                "-- plus the handoff chain: delegations WHERE ref_id = :ref, "
                "and story.chain() for the current holder"),
        "params": {"ref": ref},
        "based_on": "timeline, delegations, resolution_state · story.hero/chain/acceleration",
        "followups": [f'which domain held us longest last month',
                      f'how many incidents were reported yesterday',
                      f'what is our median resolution time this week'],
    }


def refuse(intent):
    why = intent.get("why") or "no stored definition matches this question"
    hint = intent.get("hint")
    return {
        "ok": False, "intent": "unsupported",
        "interpretation": f'I can’t answer that from the record — {why}.',
        "headline": "—", "n": 0, "n_label": "no answer computed",
        "narrative": [("I only answer questions that resolve to a stored definition: counts by date "
                       "and status, a handoff summary, the domain that held the work longest, and "
                       "median resolution time. Nothing here is guessed.")
                      + (f" {hint}." if hint else "")],
        "cites": [], "sql": None, "params": {},
        "based_on": "no table — the question did not map to a definition",
        "followups": EXAMPLES,
    }


def answer(question, now=None):
    """Question → answer dict. The only entry point the UI uses."""
    intent = parse(question)
    kind = intent["intent"]
    if kind == "count":
        return _count(intent, now)
    if kind == "median_resolution":
        return _median(intent, now)
    if kind == "held_longest":
        return _held(intent, now)
    if kind == "summary":
        return _summary(intent["ref"], now)
    return refuse(intent)
